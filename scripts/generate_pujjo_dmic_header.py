"""Serialize the independently regenerated DMIC-only NHLT as reviewed source."""
import argparse
from hashlib import sha256
from pathlib import Path

PIN = "0f6b13f2b1440e1624d53e45373093ede80ee662d97a998e817bdfec72c5d3df"

def render(data):
    if len(data) != 1955 or sha256(data).hexdigest() != PIN:
        raise ValueError("DMIC-only NHLT differs from pinned independent encoder evidence")
    if data[:4] != b"NHLT" or data[36] != 1 or sum(data) & 255:
        raise ValueError("invalid single-endpoint NHLT")
    lines = ["/* SPDX-License-Identifier: BSD-3-Clause */",
             "/* Generated by scripts/generate_pujjo_dmic_header.py.",
             " * ALSA encoder v1.2.13 pinned reference; no SSP/SoundWire routes.",
             " * NOT a hardware qualification or firmware activation grant.",
             " * SHA256: " + PIN + " */",
             "#ifndef PUJJO_DMIC_NHLT_BYTES_H",
             "#define PUJJO_DMIC_NHLT_BYTES_H",
             "static const unsigned char PujjoDmicNhlt[] = {"]
    for i in range(0, len(data), 16):
        lines.append("    " + ", ".join("0x%02x" % b for b in data[i:i+16]) + ",")
    return "\n".join(lines + ["};", "#endif", ""])

def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("input", type=Path)
    p.add_argument("header", type=Path)
    p.add_argument("--check", action="store_true")
    a = p.parse_args()
    generated = render(a.input.read_bytes())
    if a.check:
        if a.header.read_text() != generated:
            raise SystemExit("generated DMIC-only header differs from checked-in source")
        print("PASS: checked-in DMIC-only NHLT equals independent encoder artifact")
    else:
        a.header.write_text(generated)
if __name__ == "__main__":
    main()
